def get_default_loads() -> List[Dict[str, Any]]:
    """Return a fresh copy of the canonical sample electrical loads."""
    return copy.deepcopy(DEFAULT_SAMPLE_LOADS)


def calculate_connected_demand(loads: List[Dict[str, Any]], only_enabled: bool = True) -> float:
    """Calculate the sum of nominal power ratings across active loads."""
    demand = 0.0
    for l in loads:
        if only_enabled and not l.get("enabled", True):
            continue
        demand += float(l.get("power", 0.0))
    return round(demand, 2)


def evaluate_grid_operating_state(
    supply_capacity_kw: float,
    demand_kw: float
) -> Tuple[str, str, str]:
    """
    Classify the simulated grid operating state based on capacity mismatch.

    Returns:
    --------
    (state_name, badge_color_hex, descriptive_reason)
    """
    if supply_capacity_kw <= 0.0:
        return "Critical Shortage", "#EF4444", "Zero available emergency supply! Immediate blackout condition."

    ratio = demand_kw / supply_capacity_kw if supply_capacity_kw > 0 else float("inf")

    if ratio <= 1.0:
        return "Normal", "#10B981", f"Sufficient capacity ({supply_capacity_kw:.1f} kW) meets connected load ({demand_kw:.1f} kW)."
    elif ratio <= 1.4:
        deficit = round(demand_kw - supply_capacity_kw, 2)
        return "Warning", "#F59E0B", f"Moderate shortage: demand exceeds supply by {deficit:.1f} kW ({(ratio-1)*100:.0f}% deficit)."
    else:
        deficit = round(demand_kw - supply_capacity_kw, 2)
        return "Emergency", "#EF4444", f"Critical shortage: demand exceeds supply by {deficit:.1f} kW ({(ratio-1)*100:.0f}% deficit). Load shedding required!"


class SimulationEngine:
    """
    Stateful synthetic telemetry generator with physics-inspired bounded noise,
    frequency droop modeling, and voltage regulation dynamics.
    """

    def __init__(
        self,
        loads: Optional[List[Dict[str, Any]]] = None,
        supply_capacity_kw: float = DEFAULT_SUPPLY_CAPACITY_KW,
        mode: str = "Critical Shortage",
        seed: Optional[int] = 42
    ):
        self.loads = copy.deepcopy(loads) if loads is not None else get_default_loads()
        self.supply_capacity_kw = float(supply_capacity_kw)
        self.mode = mode
        self.step_count = 0
        self.is_running = True
        self.seed = seed
        self._rng = random.Random(seed) if seed is not None else random.Random()

    def set_seed(self, seed: Optional[int]) -> None:
        """Set or reset random number generator seed for reproducibility."""
        self.seed = seed
        self._rng = random.Random(seed) if seed is not None else random.Random()

    def set_mode(self, mode: str) -> None:
        """Update simulation operating mode."""
        if mode in SIMULATION_MODES:
            self.mode = mode

    def reset(self) -> None:
        """Reset internal telemetry step counter."""
        self.step_count = 0
        if self.seed is not None:
            self._rng = random.Random(self.seed)

    def generate_step(
        self,
        custom_capacity_override: Optional[float] = None,
        scheduled_power_override: Optional[float] = None
    ) -> Dict[str, Any]:
        """
        Advance one simulation step and generate a full set of electrical measurements.
        """
        self.step_count += 1
        t_sim = self.step_count

        # 1. Base supply capacity based on scenario
        if custom_capacity_override is not None:
            supply = float(custom_capacity_override)
        elif self.mode == "Normal Operation":
            # Plentiful supply (20 kW nominal +/- 0.5 kW)
            supply = 20.0 + self._rng.uniform(-0.4, 0.4)
        elif self.mode == "Moderate Shortage":
            # 11 kW nominal
            supply = 11.0 + self._rng.uniform(-0.3, 0.3)
        elif self.mode == "Critical Shortage":
            # 7 kW initial demonstration capacity
            supply = self.supply_capacity_kw + self._rng.uniform(-0.15, 0.15)
        elif self.mode == "Variable Demand":
            # Fluctuating solar / microgrid generator
            supply = 10.0 + 4.0 * math.sin(t_sim * 0.2) + self._rng.uniform(-0.5, 0.5)
        else:  # Custom Scenario
            supply = self.supply_capacity_kw

        supply = max(0.0, round(supply, 2))

        # 2. Per-load real-time power fluctuation (+/- 2% electrical variation)
        active_loads = [l for l in self.loads if l.get("enabled", True)]
        load_telemetry: List[Dict[str, Any]] = []
        total_connected_demand = 0.0

        for l in active_loads:
            base_p = float(l.get("power", 0.0))
            # Minor physical fluctuation (e.g. thermal or mechanical variation)
            jitter = self._rng.uniform(-0.03, 0.03) * base_p
            curr_p = max(0.01, round(base_p + jitter, 2))
            load_telemetry.append({
                "name": l.get("name"),
                "nominal_kw": base_p,
                "current_kw": curr_p,
                "priority": l.get("priority"),
                "criticality": l.get("criticality")
            })
            total_connected_demand += curr_p

        total_connected_demand = round(total_connected_demand, 2)

        # 3. Scheduled load power
        if scheduled_power_override is not None:
            scheduled_power = float(scheduled_power_override)
        else:
            # If not overridden, calculate with classical optimizer
            opt_res = classical_optimizer.solve_classical(self.loads, supply, only_enabled=True)
            scheduled_power = opt_res.total_selected_power

        scheduled_power = round(scheduled_power, 2)

        # 4. Grid Operating State
        op_state, badge_color, state_reason = evaluate_grid_operating_state(
            supply_capacity_kw=supply,
            demand_kw=total_connected_demand
        )

        # 5. Physics-derived electrical telemetry:
        # A. Power Factor (typically 0.93 - 0.97 for commercial building)
        pf = round(0.95 + self._rng.uniform(-0.02, 0.02), 3)

        # B. Voltage (Nominal 230 V single phase, with load droop)
        # When demand exceeds supply and unmanaged, voltage sags
        if op_state == "Emergency":
            voltage_sag = self._rng.uniform(6.0, 14.0)
        elif op_state == "Warning":
            voltage_sag = self._rng.uniform(2.0, 5.0)
        else:
            voltage_sag = self._rng.uniform(-1.5, 1.5)

        voltage_v = round(230.0 - voltage_sag, 1)

        # C. Current in Amperes: I = (P_kW * 1000) / (V * PF)
        current_a = round((scheduled_power * 1000.0) / (voltage_v * pf), 2) if voltage_v > 0 and pf > 0 else 0.0

        # D. Grid Frequency (Nominal 50.00 Hz, with governor droop dynamics)
        # Power deficit causes rotational frequency decay in generator
        freq_droop = 0.0
        if supply < total_connected_demand and scheduled_power > supply:
            # Unbalanced excess load
            excess = scheduled_power - supply
            freq_droop = min(0.6, excess * 0.05)
        elif op_state == "Emergency":
            freq_droop = self._rng.uniform(0.1, 0.35)

        frequency_hz = round(50.00 - freq_droop + self._rng.uniform(-0.02, 0.02), 2)

        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        reading = {
            "timestamp": now_str,
            "step": self.step_count,
            "mode": self.mode,
            "supply_capacity_kw": supply,
            "total_demand_kw": total_connected_demand,
            "scheduled_power_kw": scheduled_power,
            "operating_state": op_state,
            "state_color": badge_color,
            "state_reason": state_reason,
            "voltage_v": voltage_v,
            "current_a": current_a,
            "frequency_hz": frequency_hz,
            "power_factor": pf,
            "data_source_badge": DATA_SOURCE_BADGE,
            "loads_telemetry": load_telemetry
        }

        return reading


def randomize_scenario(engine: SimulationEngine) -> Dict[str, Any]:
    """Randomize scenario parameters for dynamic demonstration."""
    modes_choices = ["Normal Operation", "Moderate Shortage", "Critical Shortage", "Variable Demand"]
    chosen_mode = random.choice(modes_choices)
    engine.set_mode(chosen_mode)

    if chosen_mode == "Critical Shortage":
        engine.supply_capacity_kw = round(random.uniform(5.0, 8.0), 1)
    elif chosen_mode == "Moderate Shortage":
        engine.supply_capacity_kw = round(random.uniform(9.0, 13.0), 1)
    else:
        engine.supply_capacity_kw = round(random.uniform(16.0, 22.0), 1)

    return engine.generate_step()
